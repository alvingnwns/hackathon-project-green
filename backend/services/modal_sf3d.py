def main():
    generator = SF3DGenerator()
    # Use a sample image from the web or a local path
    test_image_path = "/tmp/test_sdxl_output.png"
    
    if not os.path.exists(test_image_path):
        print(f"⚠️ Test image not found at {test_image_path}")
